/// The shared German verb list — the ~30 most common verbs, each with the five
/// tenses a learner reaches for first: Präsens, Präteritum, Perfekt, Futur I
/// and Imperativ (modals, which have no imperative, show Konjunktiv II
/// instead). Meanings: English (fallback) + Spanish for the `es_de` courses.
/// Published to `assets/content/shared/verbs/de.json`.
const List<String> _p = ['ich', 'du', 'er/sie/es', 'wir', 'ihr', 'sie/Sie'];
const List<String> _habenPraesens = [
  'habe', 'hast', 'hat', 'haben', 'habt', 'haben',
];
const List<String> _seinPraesens = ['bin', 'bist', 'ist', 'sind', 'seid', 'sind'];
const List<String> _werdenPraesens = [
  'werde', 'wirst', 'wird', 'werden', 'werdet', 'werden',
];

List<ConjugationForm> _zip(List<String> persons, List<String> forms) => [
  for (var i = 0; i < persons.length; i++)
    ConjugationForm(person: persons[i], form: forms[i]),
];

const List<String> _wuerde = [
  'würde', 'würdest', 'würde', 'würden', 'würdet', 'würden',
];

/// Builds a verb from its principal parts: Perfekt (aux Präsens + Partizip II)
/// and Futur I (werden + infinitive) are derived, so the compound tenses can
/// never drift from the parts. The fifth table is [imperativ] (du/ihr/Sie)
/// when the verb has a natural one, else [konjunktiv2] (modals), else the
/// derived würde-Konjunktiv. Passing both imperativ and konjunktiv2 yields
/// six tables (sein/haben/werden, whose wäre/hätte/würde forms learners meet
/// from B1 on). Separable verbs write their finite forms split
/// ("stehe … auf"); Perfekt/Futur still derive correctly from the partizip
/// and the joined infinitive.
VerbEntry _v(
  String infinitive,
  String english,
  String es, {
  required List<String> praesens,
  required List<String> praeteritum,
  required String partizip,
  String aux = 'haben',
  List<String>? imperativ,
  List<String>? konjunktiv2,
}) {
  final auxForms = aux == 'sein' ? _seinPraesens : _habenPraesens;
  return VerbEntry(
    verb: infinitive,
    english: english,
    meanings: {'es': es},
    sets: [
      ConjugationSet(label: 'Präsens', forms: _zip(_p, praesens)),
      ConjugationSet(label: 'Präteritum', forms: _zip(_p, praeteritum)),
      ConjugationSet(
        label: 'Perfekt',
        forms: _zip(_p, [for (final a in auxForms) '$a $partizip']),
      ),
      ConjugationSet(
        label: 'Futur I',
        forms: _zip(_p, [for (final w in _werdenPraesens) '$w $infinitive']),
      ),
      if (imperativ != null)
        ConjugationSet(
          label: 'Imperativ',
          forms: _zip(const ['(du)', '(ihr)', '(Sie)'], imperativ),
        ),
      if (imperativ == null || konjunktiv2 != null)
        ConjugationSet(
          label: 'Konjunktiv II',
          forms: _zip(
            _p,
            konjunktiv2 ?? [for (final w in _wuerde) '$w $infinitive'],
          ),
        ),
    ],
  );
}

/// Inseparable prefixes — verbs starting with one build their Partizip II
/// without `ge-` (besucht, erklärt, verkauft, …).
const List<String> _inseparable = [
  'be', 'ge', 'emp', 'ent', 'er', 'miss', 'ver', 'zer', 'über', 'unter',
];

/// A fully regular (weak) verb, all forms derived from the infinitive:
/// -e- padding for stems in -d/-t (wartest) and consonant+m/n (öffnest, but
/// wohnst/trennst stay bare), the s/ß/x/z du-merge (tanzt), -ern infinitives
/// (feiern → feiere), -ieren and inseparable prefixes without ge- participles.
/// [noImperative] verbs (kosten, fehlen, …) show würde-Konjunktiv II instead.
VerbEntry _vr(
  String infinitive,
  String english,
  String es, {
  String aux = 'haben',
  bool noImperative = false,
}) {
  final ern = infinitive.endsWith('ern');
  final stem = infinitive.substring(0, infinitive.length - (ern ? 1 : 2));
  final beforeLast = stem.length > 1 ? stem[stem.length - 2] : '';
  final pad = !ern &&
      (stem.endsWith('d') ||
          stem.endsWith('t') ||
          ((stem.endsWith('m') || stem.endsWith('n')) &&
              !'aeiouäöülrhmn'.contains(beforeLast)));
  final sMerge = RegExp(r'[sßxz]$').hasMatch(stem);
  final du = pad ? '${stem}est' : (sMerge ? '${stem}t' : '${stem}st');
  final erIhr = pad ? '${stem}et' : '${stem}t';
  final praet = pad ? '${stem}ete' : '${stem}te';
  final hasPrefix = _inseparable.any(
    (p) => infinitive.startsWith(p) && infinitive.length > p.length + 3,
  );
  final partizip = infinitive.endsWith('ieren') || hasPrefix
      ? erIhr
      : 'ge$erIhr';
  return _v(
    infinitive,
    english,
    es,
    praesens: ['${stem}e', du, erIhr, infinitive, erIhr, infinitive],
    praeteritum: [
      praet, '${praet}st', praet, '${praet}n', '${praet}t', '${praet}n',
    ],
    partizip: partizip,
    aux: aux,
    imperativ: noImperative
        ? null
        : [
            pad || ern || infinitive.endsWith('ieren') ? '${stem}e' : stem,
            erIhr,
            '$infinitive Sie',
          ],
  );
}

/// An impersonal verb (es regnet): one `es` row per tense instead of a full
/// person table nobody would ever use.
VerbEntry _vEs(
  String infinitive,
  String english,
  String es, {
  required String praesens,
  required String praeteritum,
  required String partizip,
  String aux = 'haben',
}) {
  ConjugationSet one(String label, String form) =>
      ConjugationSet(label: label, forms: [
        ConjugationForm(person: 'es', form: form),
      ]);
  return VerbEntry(
    verb: infinitive,
    english: english,
    meanings: {'es': es},
    sets: [
      one('Präsens', praesens),
      one('Präteritum', praeteritum),
      one('Perfekt', '${aux == 'sein' ? 'ist' : 'hat'} $partizip'),
      one('Futur I', 'wird $infinitive'),
      one('Konjunktiv II', 'würde $infinitive'),
    ],
  );
}

