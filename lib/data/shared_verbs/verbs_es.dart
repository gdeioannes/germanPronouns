/// The shared Spanish verb list — the ~25 most common verbs with the five
/// tenses a learner needs first: presente, pretérito indefinido, pretérito
/// imperfecto, futuro and pretérito perfecto. Imperfecto (regular except
/// ser/ir/ver), futuro (stem + é/ás/á/emos/éis/án) and perfecto (haber +
/// participio) are derived from the principal parts. Meanings: German (the
/// `de_es` course's main language) + English fallback. Published to
/// `assets/content/shared/verbs/es.json`.
const List<String> _p = [
  'yo', 'tú', 'él/ella/usted', 'nosotros', 'vosotros', 'ellos/ustedes',
];
const List<String> _haberPresente = ['he', 'has', 'ha', 'hemos', 'habéis', 'han'];
const List<String> _futuroEndings = ['é', 'ás', 'á', 'emos', 'éis', 'án'];

List<ConjugationForm> _zip(List<String> forms) => [
  for (var i = 0; i < _p.length; i++)
    ConjugationForm(person: _p[i], form: forms[i]),
];

List<String> _withEndings(String stem, List<String> endings) => [
  for (final e in endings) '$stem$e',
];

List<String> _imperfectoRegular(String infinitive) => _withEndings(
  infinitive.substring(0, infinitive.length - 2),
  infinitive.endsWith('ar')
      ? const ['aba', 'abas', 'aba', 'ábamos', 'abais', 'aban']
      : const ['ía', 'ías', 'ía', 'íamos', 'íais', 'ían'],
);

/// Presente de subjuntivo derived from the yo-form (conozco → conozca);
/// verbs whose nosotros/vosotros forms lose the stem change (podamos) or
/// need spelling fixes (llegue) pass an override.
List<String> _subjuntivoRegular(String infinitive, String yo) => _withEndings(
  yo.endsWith('o') ? yo.substring(0, yo.length - 1) : yo,
  infinitive.endsWith('ar')
      ? const ['e', 'es', 'e', 'emos', 'éis', 'en']
      : const ['a', 'as', 'a', 'amos', 'áis', 'an'],
);

VerbEntry _v(
  String infinitive,
  String english,
  String de, {
  required List<String> presente,
  required List<String> indefinido,
  required String participio,
  List<String>? imperfecto,
  String? futuroStem,
  List<String>? subjuntivo,
}) => VerbEntry(
  verb: infinitive,
  english: english,
  meanings: {'de': de},
  sets: [
    ConjugationSet(label: 'Presente', forms: _zip(presente)),
    ConjugationSet(label: 'Pretérito indefinido', forms: _zip(indefinido)),
    ConjugationSet(
      label: 'Pretérito imperfecto',
      forms: _zip(imperfecto ?? _imperfectoRegular(infinitive)),
    ),
    ConjugationSet(
      label: 'Futuro',
      forms: _zip(_withEndings(futuroStem ?? infinitive, _futuroEndings)),
    ),
    ConjugationSet(
      label: 'Pretérito perfecto',
      forms: _zip([for (final h in _haberPresente) '$h $participio']),
    ),
    // The de_es course drills the subjuntivo and the conditional from B1 on,
    // so their forms must be tappable too.
    ConjugationSet(
      label: 'Presente de subjuntivo',
      forms: _zip(subjuntivo ?? _subjuntivoRegular(infinitive, presente[0])),
    ),
    ConjugationSet(
      label: 'Condicional',
      forms: _zip(
        _withEndings(
          futuroStem ?? infinitive,
          const ['ía', 'ías', 'ía', 'íamos', 'íais', 'ían'],
        ),
      ),
    ),
  ],
);

/// The impersonal weather verb (llueve): one row per tense.
VerbEntry _vLlueve() {
  ConjugationSet one(String label, String form) =>
      ConjugationSet(label: label, forms: [
        ConjugationForm(person: '(3ª)', form: form),
      ]);
  return VerbEntry(
    verb: 'llover',
    english: 'to rain',
    meanings: const {'de': 'regnen'},
    sets: [
      one('Presente', 'llueve'),
      one('Pretérito indefinido', 'llovió'),
      one('Pretérito imperfecto', 'llovía'),
      one('Futuro', 'lloverá'),
      one('Presente de subjuntivo', 'llueva'),
      one('Condicional', 'llovería'),
    ],
  );
}

